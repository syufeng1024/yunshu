-- 0030 t_api_key.key_enc：把密钥明文以信封加密留在库里，「复制密钥」才有数据来源。
--
-- 为什么需要它：建表时只存 key_hash（SHA-256）、key_prefix、key_last4，明文只在
-- 创建响应里出现一次。用户把密钥配进客户端后一旦丢失，唯一出路是轮换（旧密钥
-- 立即失效），「我只是想再看一眼」没有解法。需求方 2026-11-05 明确要求
-- 「密钥不能完整显示，但必须可复制」。
--
-- 为什么是信封加密而不是明文列：密文由 cryptobox 用 CHANNEL_KEY_KEK 封装（v1: 前缀
-- 自带密钥版本），KEK 轮换时可识别版本并重加密；只拿到库 dump 拿不到 KEK 时无法还原。
--
-- 安全边界写在这里，别只写在代码注释里：数据库与 KEK 同时泄露时，所有历史密钥都
-- 可还原——这是「可复制」的代价，安全性弱于纯哈希。所以读取路径必须二次确认 +
-- 写审计（action=VIEW_SECRET），并且只在用户主动点击时发生，列表与详情接口都不带明文。
--
-- 存量行 key_enc 为 NULL，且无法回填：哈希不可逆，密文只能从明文生成。详情页对这类
-- 行明确提示「创建于加密存储上线前，无法找回，可轮换」，不假装能复制。
--
-- 回滚见 0030_add_api_key_secret.down.sql：只 DROP 列。密文只是明文的副本，
-- 鉴权链路读的是 key_hash，掉列不影响任何正在使用的密钥。

ALTER TABLE t_api_key
  ADD COLUMN key_enc varbinary(512) DEFAULT NULL
    COMMENT '密钥明文的信封密文（cryptobox v1: 前缀）；NULL = 加密存储上线前创建，不可还原'
    AFTER key_last4;
